/* 软件延时 */
void delay (uint32_t count)
{
	for(; count!=0; count--);
}
void Task1( void *p_arg )
{	OS_ERR err;
	  for( ;; ){
		flag1 = 1;
		OSTimeDly(2);	
    
		OSTaskSuspend(&Task3TCB,&err);	//将任务3挂起		
		
		flag1 = 0;
		OSTimeDly(2);	
    
		OSTaskResume(&Task3TCB,&err);	  //将任务3恢复
	}
}

void Task2( void *p_arg )
{
	for( ;; )
    {
		flag2 = 1;
		delay(0xff);		
		flag2 = 0;
		delay(0xff);
	}
}

void Task3( void *p_arg )
{
	for( ;; )
    {
		flag3 = 1;
		delay(0xff);		
		flag3 = 0;
		delay(0xff);
	}
}
