void Write_SPI_Data(unsigned char ucData)    //SPI数据发送函数
{
    unsigned char i = 8;
	  LPC_GPIO0->FIOSET |= (1<<10);   //   DC   = 1;  数据
		LPC_GPIO0->FIOCLR |= (1<<7);   //    SCL  = 0;  时钟引脚
   
    while (i--)
    {
        if (ucData & 0x80)
        {
            LPC_GPIO0->FIOSET |= (1<<8);  // SDA = 1;   //把内容发过去
        } 
        else
        {
            LPC_GPIO0->FIOCLR	|= (1<<8);  // SDA = 0;
        }
         
        LPC_GPIO0->FIOSET |= (1<<7);   //    SCL = 1;  //给一个下降沿
       // _nop_();
        LPC_GPIO0->FIOCLR |= (1<<7);   //    SCL  = 0; 
        ucData <<= 1;    
    }

    return;
}

/*****************************************************************************/
void Write_SPI_Command(unsigned char ucCmd)  //SPI命令发送函数
{
    unsigned char i = 8;
    LPC_GPIO0->FIOCLR |= (1<<10);   //   DC  = 0;  命令
    LPC_GPIO0->FIOCLR |= (1<<7);   //    SCL = 0;  时钟引脚
    while (i--)
    {
        if (ucCmd & 0x80)
        {
             LPC_GPIO0->FIOSET |= (1<<8);  // SDA = 1; //把内容发过去
        }
        else
        {
            LPC_GPIO0->FIOCLR	|= (1<<8);  // SDA = 0;
        }
          
        LPC_GPIO0->FIOSET |= (1<<7);   //    SCL = 1;   //给一个下降沿
        //_nop_();
        LPC_GPIO0->FIOCLR |= (1<<7);   //    SCL  = 0;  
        ucCmd <<= 1;   
    }  

    return;
}

void fill_picture(unsigned char fill_Data)   //填充数据
{
	unsigned char m,n;
	for(m=0;m<8;m++)
	{
		Write_SPI_Command(0xb0+m);	 //设置页地址后三位控制0~7页，其低三位的值对应着GRAM的页地址。
		Write_SPI_Command(0x00);	 //用于设置显示时的起始列地址低四位。
		Write_SPI_Command(0x10);     //用于设置显示时的起始列地址高四位。
		for(n=0;n<128;n++)
			{
				Write_SPI_Data(fill_Data);
			}
	}
}
