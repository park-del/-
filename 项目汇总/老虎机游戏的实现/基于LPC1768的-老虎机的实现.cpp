void OLED_Drawbmp(uint8_t x,uint8_t y,char *bmp,uint8_t m,uint8_t n)//OLED画图像函数,图像一共有128*64（128为图像的长，64位图像的宽，总共有128*64个点），x、y是定位到某一个位置，总共由128列，64行
//x是定位到某一列的，y是定位到某一行的，bmp这个数组存放的是某个图像的模，后面的m与n分别表示了bmp这个图像的长和宽。（即是bmp和m和n共同表示了一个图像，x和y是表示这个图像显示的位置）
{   
	//x为列，y为行，*bmp为数组，n为高度，m为宽度
        uint8_t i,j,page1=y/8,page2=n/8+page1,a=0x0F&x,b=(0xF0&x)>>4|0x10; //page是这个图像起始的页数，page2是这个图像末尾的页数，page2-page1是这个图像一共占了多少页
//a表示        
	
	      for(i=0;page1<page2;i++,page1++)
        {
                Write_SPI_Command(0xb0+page1);
                Write_SPI_Command(a);
                Write_SPI_Command(b);
                for(j=0;j<m;j++)
                {
                        frame[page1*128+x+j]|=(bmp[i*m+j]<<y%8);;
                        frame[page1*128+x+j]&=(0xFF>>(8-y%8)|(bmp[i*m+j]<<y%8));
                        Write_SPI_Data(frame[page1*128+x+j]);
                }
          if(page1<7&&y%8)
                {
                       Write_SPI_Command(0xb0+page1+1);
                       Write_SPI_Command(a);
                       Write_SPI_Command(b);
                  for(j=0;j<m;j++)
                  {
                          frame[(page1+1)*128+x+j]|=(bmp[i*m+j]>>(8-y%8));
                                frame[(page1+1)*128+x+j]&=((0xFF<<y%8)|(bmp[i*m+j]>>(8-y%8)));
                          Write_SPI_Data(frame[(page1+1)*128+x+j]);
                  }
                }
        }
}

